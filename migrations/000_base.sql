create table public.eventos_coletados (
  id bigint generated by default as identity primary key,
  numero_evento text not null,
  data_evento text,
  uf text,
  descricao text,
  quantidade text,
  unidade text,
  data_coleta timestamptz default now(),
  titulo text,
  marca text,
  conta text not null default 'filial1',
  data_inicio date,
  constraint eventos_coletados_conta_evento_titulo_key unique (conta, numero_evento, titulo)
);
create index idx_numero_evento on public.eventos_coletados (numero_evento);
create index eventos_coletados_data_inicio_idx on public.eventos_coletados (data_inicio);
alter table public.eventos_coletados enable row level security;
create policy "Permitir leitura para todos" on public.eventos_coletados for select to public using (true);
create policy "Permitir inserção para todos" on public.eventos_coletados for insert to public with check (true);

create table public.perfis (
  user_id uuid primary key references auth.users(id) on delete cascade,
  email text,
  nome text,
  papel text not null default 'operador' check (papel in ('admin','operador')),
  ativo boolean not null default true,
  criado_em timestamptz not null default now(),
  atualizado_em timestamptz not null default now()
);
alter table public.perfis enable row level security;

create function public.eh_admin() returns boolean
  language sql stable security definer set search_path to ''
as $$
  select exists (
    select 1 from public.perfis
    where user_id = auth.uid() and papel = 'admin' and ativo
  );
$$;

create policy "perfil: cada um ve o seu, admin ve todos" on public.perfis
  for select to authenticated using (user_id = (select auth.uid()) or eh_admin());

create function public.criar_perfil_novo_usuario() returns trigger
  language plpgsql security definer set search_path to ''
as $$
begin
  insert into public.perfis (user_id, email) values (new.id, new.email)
  on conflict (user_id) do nothing;
  return new;
end;
$$;
create trigger ao_criar_usuario_criar_perfil after insert on auth.users
  for each row execute function public.criar_perfil_novo_usuario();

create table public.credenciais_coupa (
  conta_id text primary key check (conta_id ~ '^[a-z0-9_-]{1,30}$' and conta_id <> 'todas'),
  nome text,
  usuario text check (usuario is null or char_length(usuario) <= 200),
  senha_cifrada text,
  atualizado_em timestamptz not null default now(),
  atualizado_por text
);
alter table public.credenciais_coupa enable row level security;
